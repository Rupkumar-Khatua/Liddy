/**
 * Returns localized string for the specified key and language code.
 * Falls back to English if translation is missing.
 */
export const getTranslation = (key: string, langCode: string, defaultText?: string): string => {
  const entry = TRANSLATION_DICTIONARY[key];
  if (!entry) return defaultText || key;
  return entry[langCode] || entry['en'] || defaultText || key;
};

/**
 * Triggers full-page translation for the whole app DOM in stealth mode
 * without any UI indicators or "Powered by" mentions.
 */
export const triggerGlobalTranslation = (langCode: string) => {
  const gLang = langCode === 'zh' ? 'zh-CN' : langCode;
  
  try {
    const hostname = window.location.hostname;
    if (langCode === 'en') {
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;`;
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=${hostname}; path=/;`;
      document.cookie = `googtrans=/en/en; path=/;`;
    } else {
      document.cookie = `googtrans=/en/${gLang}; path=/;`;
      document.cookie = `googtrans=/en/${gLang}; domain=${hostname}; path=/;`;
    }

    const selectCombo = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
    if (selectCombo) {
      if (selectCombo.value !== gLang) {
        selectCombo.value = gLang;
      }
      selectCombo.dispatchEvent(new Event('change', { bubbles: true }));
      selectCombo.dispatchEvent(new Event('input', { bubbles: true }));
    } else {
      let attempts = 0;
      const interval = setInterval(() => {
        attempts++;
        const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
        if (select) {
          select.value = gLang;
          select.dispatchEvent(new Event('change', { bubbles: true }));
          select.dispatchEvent(new Event('input', { bubbles: true }));
          clearInterval(interval);
        } else if (attempts > 12) {
          clearInterval(interval);
        }
      }, 120);
    }
  } catch (err) {
    console.warn('Translation trigger note', err);
  }
};

/**
 * Custom hook to instantly synchronize translation whenever a dynamic
 * component (e.g. NewsDetailModal, CompanyDetailModal) mounts into the DOM.
 */
export const useTranslationSync = (langCode: string, isActive: boolean = true) => {
  useEffect(() => {
    if (!isActive || !langCode || langCode === 'en') return;

    // Immediate sync pulse
    triggerGlobalTranslation(langCode);

    // Staggered micro-pulses to translate newly created React Portal nodes
    const timer1 = setTimeout(() => triggerGlobalTranslation(langCode), 40);
    const timer2 = setTimeout(() => triggerGlobalTranslation(langCode), 140);
    const timer3 = setTimeout(() => triggerGlobalTranslation(langCode), 320);

    return () => {
      clearTimeout(timer1);
      clearTimeout(timer2);
      clearTimeout(timer3);
    };
  }, [langCode, isActive]);
};

